<?php

/**
 * The harness's composer.json and phpunit.xml: this core from its checkout,
 * each driver from a checkout under /omnisearch/plugins when there is one,
 * from GitHub (branch 1.x) otherwise, omnisense/contracts the same way from
 * /omnisense/contracts; every package's tests in one run.
 * Files are rewritten only when they change, so the entrypoint knows when
 * to install.
 */
$plugins = require __DIR__.'/plugins.php';
$core = '/omnisearch/core';
$local = '/omnisearch/plugins';
$out = '/harness';

$repositories = [['type' => 'path', 'url' => $core, 'options' => ['symlink' => true, 'versions' => ['omnisense/omnisearch' => '1.x-dev']]]];
$require = ['omnisense/omnisearch' => '1.x-dev'];
$tests = ['Omnisearch\\Tests\\' => "$core/Tests/"];
$suites = ['core' => "$core/Tests"];
$drivers = [];

// omnisense/contracts, the kernel the family builds on: its checkout under /omnisense/contracts
// (OMNISENSE_CONTRACTS in .env) when there is one, its tests run beside the family's; GitHub otherwise.
$contracts = '/omnisense/contracts';
$meta = is_file("$contracts/composer.json") ? json_decode((string) file_get_contents("$contracts/composer.json"), true) : null;
if (($meta['name'] ?? null) === 'omnisense/contracts') {
    $repositories[] = ['type' => 'path', 'url' => $contracts, 'options' => ['symlink' => true, 'versions' => ['omnisense/contracts' => '1.x-dev']]];
    $tests['Omnisense\\Contracts\\Tests\\'] = "$contracts/Tests/";
    $suites['contracts'] = "$contracts/Tests";
    $drivers['contracts'] = 'checkout';
} else {
    $repositories[] = ['type' => 'git', 'url' => 'https://github.com/glitchr-omnisense/contracts.git'];
    $drivers['contracts'] = 'github';
}
$require['omnisense/contracts'] = '1.x-dev';
foreach ($plugins as $slug => [$testsNs]) {
    $name = "omnisearch/$slug";
    $dir = "$local/$slug";
    $meta = is_file("$dir/composer.json") ? json_decode((string) file_get_contents("$dir/composer.json"), true) : null;
    if (($meta['name'] ?? null) === $name) {
        $repositories[] = ['type' => 'path', 'url' => $dir, 'options' => ['symlink' => true, 'versions' => [$name => '1.x-dev']]];
        $testDir = "$dir/Tests";
        $drivers[$slug] = 'checkout';
    } else {
        // A plain git clone over HTTPS: no GitHub API (anonymous calls are rate limited), no ssh in the image.
        $repositories[] = ['type' => 'git', 'url' => "https://github.com/glitchr-omnisense/omnisearch-$slug.git"];
        $testDir = "$out/vendor/omnisearch/$slug/Tests";
        $drivers[$slug] = 'github';
    }
    $require[$name] = '1.x-dev';
    $tests[$testsNs] = $testDir.'/';
    $suites[$slug] = $testDir;
}

$composer = [
    'name' => 'omnisense/omnisearch-harness',
    'description' => 'omnisense/omnisearch with every driver: generated by docker/harness/setup.php, do not edit.',
    'type' => 'project',
    'license' => 'MIT',
    'repositories' => $repositories,
    'require' => $require + [
        'php' => '>=8.2',
        'ext-pdo_sqlite' => '*',
        'doctrine/orm' => '^3.0',
    ],
    'require-dev' => [
        'doctrine/doctrine-bundle' => '^2.13|^3.0',
        'phpstan/phpstan' => '^2.1',
        'phpunit/phpunit' => '^11.0',
        'symfony/framework-bundle' => '^7.0|^8.0',
        'symfony/cache' => '^7.0|^8.0',
        'symfony/config' => '^7.0|^8.0',
        'symfony/console' => '^7.0|^8.0',
        'symfony/dependency-injection' => '^7.0|^8.0',
        // Installed so that php-http's discovery gives typesense-php Symfony's
        // PSR-18 client, as in an application: its network failures are the
        // PSR-18 interfaces' only, which a driver must catch.
        'symfony/http-client' => '^7.0|^8.0',
        'symfony/http-kernel' => '^7.0|^8.0',
    ],
    'autoload-dev' => ['psr-4' => $tests],
    'minimum-stability' => 'dev',
    'prefer-stable' => true,
    'config' => ['sort-packages' => true],
];
$json = json_encode($composer, \JSON_PRETTY_PRINT | \JSON_UNESCAPED_SLASHES)."\n";
if (!is_file("$out/composer.json") || file_get_contents("$out/composer.json") !== $json) {
    file_put_contents("$out/composer.json", $json);
    echo "composer.json composed: ", implode(', ', array_map(static fn ($s, $f) => "$s ($f)", array_keys($drivers), $drivers)), "\n";
}

$xml = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<phpunit xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\" xsi:noNamespaceSchemaLocation=\"vendor/phpunit/phpunit/phpunit.xsd\" bootstrap=\"vendor/autoload.php\" colors=\"true\" failOnWarning=\"true\" cacheDirectory=\".phpunit.cache\">\n    <testsuites>\n";
foreach ($suites as $suite => $dir) {
    $xml .= "        <testsuite name=\"$suite\"><directory>$dir</directory></testsuite>\n";
}
$xml .= "    </testsuites>\n</phpunit>\n";
if (!is_file("$out/phpunit.xml") || file_get_contents("$out/phpunit.xml") !== $xml) {
    file_put_contents("$out/phpunit.xml", $xml);
}
